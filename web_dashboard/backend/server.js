/**
 * GET /api/bots/:id/settings/content-mode - Get content mode
 */
app.get('/api/bots/:id/settings/content-mode', authMiddleware, async (req, res) => {
    const bot = await Bot.findByPk(req.params.id);
    
    if (!bot) {
        return res.status(404).json({ error: 'Bot not found' });
    }
    
    res.json({
        mode: bot.explicitContentMode,
        options: ['fully_filtered', 'mature', 'explicit'],
        description: getContentTypeDescription(bot.explicitContentMode)
    });
});

function getContentTypeDescription(mode) {
    const descriptions = {
        'fully_filtered': 'No restrictions - SFW-only responses',
        'mature': 'Artistic/contextual explicit content when scene-appropriate',
        'explicit': 'Full freedom - all content permitted'
    };
    
    return descriptions[mode] || '';
}

/**
 * POST /api/bots/:id/settings/content-mode - Update content mode
 */
app.post('/api/bots/:id/settings/content-mode', authMiddleware, async (req, res) => {
    const bot = await Bot.findByPk(req.params.id);
    
    if (!bot) {
        return res.status(404).json({ error: 'Bot not found' });
    }
    
    const { mode } = req.body;
    
    if (!['fully_filtered', 'mature', 'explicit'].includes(mode)) {
        return res.status(400).json({ 
            error: 'Invalid content mode. Must be one of: fully_filtered, mature, explicit' 
        });
    }
    
    await bot.update({ explicitContentMode: mode });
    
    res.json({
        message: `Content mode set to: ${mode}`,
        mode
    });
});

