const express = require('express');
const cors = require('cors');
const bcrypt = require('bcrypt');
const jwt = require('jsonwebtoken');
const { Sequelize, DataTypes } = require('sequelize');

const app = express();

// Middleware
app.use(cors({
    origin: process.env.FRONTEND_URL || 'http://localhost:3000',
    credentials: true
}));
app.use(express.json());

// =============================================
// DATABASE CONFIGURATION (PostgreSQL)
// =============================================
const sequelize = new Sequelize(
    process.env.POSTGRES_URL,
    {
        dialect: 'postgres',
        logging: console.log
    }
);

// Models (from shared schema.sql)
const User = sequelize.define('users', {
    id: { type: DataTypes.UUID, defaultValue: DataTypes.UUIDV4, primaryKey: true },
    email: { type: DataTypes.STRING(255), unique: true, allowNull: false },
    passwordHash: { type: DataTypes.STRING(255), allowNull: false },
    fullName: { type: DataTypes.STRING(255) },
    avatarUrl: { type: DataTypes.TEXT }
}, {
    tableName: 'users',
    timestamps: true
});

const Bot = sequelize.define('bots', {
    id: { type: DataTypes.UUID, defaultValue: DataTypes.UUIDV4, primaryKey: true },
    userId: { type: DataTypes.UUID, references: { model: User, key: 'id' }, onDelete: 'CASCADE' },
    name: { type: DataTypes.STRING(100), allowNull: false },
    ageRange: { type: DataTypes.STRING(50) },
    personality: { type: DataTypes.TEXT },
    speechStyle: { type: DataTypes.STRING(100) },
    backstory: { type: DataTypes.TEXT },
    exampleDialogue: { type: DataTypes.JSONB, defaultValue: [] },
    extraRules: { type: DataTypes.TEXT },
    explicitContentMode: { 
        type: DataTypes.ENUM('fully_filtered', 'mature', 'explicit'),
        defaultValue: 'fully_filtered' 
    },
    discordBotTokenEncrypted: { type: DataTypes.TEXT },
    applicationId: { type: DataTypes.STRING(100) },
    redirectUris: { type: DataTypes.JSONB, defaultValue: [] },
    dmOnlyMode: { type: DataTypes.BOOLEAN, defaultValue: true },
    isActive: { type: DataTypes.BOOLEAN, defaultValue: false }
}, {
    tableName: 'bots',
    timestamps: true
});

const Memory = sequelize.define('memories', {
    id: { type: DataTypes.UUID, defaultValue: DataTypes.UUIDV4, primaryKey: true },
    botId: { 
        type: DataTypes.UUID, 
        references: { model: Bot, key: 'id' }, 
        onDelete: 'CASCADE' 
    },
    category: { type: DataTypes.STRING(50) },
    title: { type: DataTypes.STRING(255), allowNull: false },
    content: { type: DataTypes.JSONB, allowNull: false },
    isAutoGenerated: { type: DataTypes.BOOLEAN, defaultValue: false },
    autoGenerationReason: { type: DataTypes.TEXT }
}, {
    tableName: 'memories',
    timestamps: true
});

const MemorySession = sequelize.define('memory_sessions', {
    id: { type: DataTypes.UUID, defaultValue: DataTypes.UUIDV4, primaryKey: true },
    botId: { 
        type: DataTypes.UUID, 
        references: { model: Bot, key: 'id' }, 
        onDelete: 'CASCADE' 
    },
    windowSize: { type: DataTypes.INTEGER, defaultValue: 50 },
    autoExpireHours: { type: DataTypes.INTEGER, defaultValue: 72 }
}, {
    tableName: 'memory_sessions',
    timestamps: true
});

// =============================================
// AUTHENTICATION MIDDLEWARE
// =============================================
const authMiddleware = async (req, res, next) => {
    const token = req.headers.authorization?.split(' ')[1];  // Bearer TOKEN
    
    if (!token) {
        return res.status(401).json({ error: 'Missing authorization token' });
    }
    
    try {
        const decoded = jwt.verify(token, process.env.JWT_SECRET);
        req.user = decoded;
        next();
    } catch (error) {
        res.status(401).json({ error: 'Invalid or expired token' });
    }
};

